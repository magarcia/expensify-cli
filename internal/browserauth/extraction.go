package browserauth

// Anonymous sessions also have device credentials; verify the signed-in session
// and matching identity in one snapshot.
const extractionJS = `(async () => {
  if (!['https://new.expensify.com', 'https://www.expensify.com'].includes(location.origin)) return null;
  return await new Promise(resolve => {
    let database;
    let transaction;
    let finished = false;
    const finish = value => {
      if (finished) return;
      finished = true;
      clearTimeout(timer);
      if (database) database.close();
      resolve(value);
    };
    const timer = setTimeout(() => {
      if (transaction) {
        try { transaction.abort(); } catch {}
      }
      finish(null);
    }, 1500);
    (async () => {
      if (typeof indexedDB.databases === 'function') {
        const databases = await indexedDB.databases();
        if (!databases.some(database => database.name === 'OnyxDB')) {
          finish(null);
          return;
        }
      }
      if (finished) return;
      const request = indexedDB.open('OnyxDB');
      request.onupgradeneeded = () => request.transaction.abort();
      request.onerror = request.onblocked = () => finish(null);
      request.onsuccess = () => {
        database = request.result;
        if (finished) {
          database.close();
          return;
        }
        if (!database.objectStoreNames.contains('keyvaluepairs')) {
          finish(null);
          return;
        }
        try {
          transaction = database.transaction('keyvaluepairs', 'readonly');
        } catch {
          finish(null);
          return;
        }
        const store = transaction.objectStore('keyvaluepairs');
        const credentialsRequest = store.get('credentials');
        const sessionRequest = store.get('session');
        transaction.onabort = transaction.onerror = () => {
          finish(null);
        };
        transaction.oncomplete = () => {
          const credentials = credentialsRequest.result;
          const session = sessionRequest.result;
          if (!credentials || !session ||
              typeof credentials.autoGeneratedLogin !== 'string' || !credentials.autoGeneratedLogin ||
              typeof credentials.autoGeneratedPassword !== 'string' || !credentials.autoGeneratedPassword ||
              typeof session.authToken !== 'string' || !session.authToken ||
              typeof session.email !== 'string' || !session.email ||
              !Number.isSafeInteger(session.accountID) || session.accountID <= 0 ||
              ['anonymousAccount', 'support', 'delegate'].includes(session.authTokenType) ||
              (credentials.accountID != null && credentials.accountID !== session.accountID)) {
            finish(null);
            return;
          }
          finish({
            partnerUserID: credentials.autoGeneratedLogin,
            partnerUserSecret: credentials.autoGeneratedPassword,
            authToken: session.authToken,
            email: session.email,
            accountID: session.accountID
          });
        };
      };
    })().catch(() => finish(null));
  });
})()`
