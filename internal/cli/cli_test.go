func TestParseCredentialsShapes(t *testing.T) {
	for _, data := range []string{
		`{"partnerUserID":"device","partnerUserSecret":"secret","authToken":"session"}`,
		`{"autoGeneratedLogin":"device","autoGeneratedPassword":"secret","authToken":"session"}`,
		`{"session":{"autoGeneratedLogin":"device","autoGeneratedPassword":"secret","authToken":"session"}}`,
		`{"credentials":{"autoGeneratedLogin":"device","autoGeneratedPassword":"secret","authToken":"session"}}`,
		`{"DEVICE_SESSION_CREDENTIALS":"{\"partnerUserID\":\"device\",\"partnerUserSecret\":\"secret\",\"authToken\":\"session\"}"}`,
	} {
		credentials, err := parseCredentials(strings.NewReader(data))
		if err != nil {
			t.Fatal(err)
		}
		if credentials.PartnerUserID != "device" || credentials.PartnerUserSecret != "secret" || credentials.AuthToken != "session" {
			t.Fatalf("Unexpected fields for %s", data)
		}
	}
}

func TestCredentialErrorsNeverExposeSecrets(t *testing.T) {
	for _, data := range []string{`{"partnerUserSecret":"sensitive"}`, `{"authToken":"sensitive"} {}`, `{"DEVICE_SESSION_CREDENTIALS":"sensitive"}`} {
		_, err := parseCredentials(strings.NewReader(data))
		if err == nil || strings.Contains(err.Error(), "sensitive") {
			t.Fatalf("Expected safe error, got %v", err)
		}
	}
	if _, err := parseCredentials(strings.NewReader(`{"partnerUserSecret":"sensitive","credentials":{"autoGeneratedLogin":"different-account"}}`)); err == nil {
		t.Fatal("Nested credential record inherited outer credentials")
	}
}

