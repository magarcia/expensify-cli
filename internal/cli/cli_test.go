func TestJSONModeSuppressesVerboseProgress(t *testing.T) {
	var stderr bytes.Buffer
	a := &application{errOut: &stderr, opts: options{format: "json", verbose: 2}}
	stop := a.progress("Running expense list")
	stop()
	code := a.finish(fault.New("API-002", "Invalid API response.", "Try again later.", 10))
	if code != 10 {
		t.Fatalf("Unexpected exit: %d", code)
	}
	var envelope map[string]any
	if err := json.Unmarshal(stderr.Bytes(), &envelope); err != nil {
		t.Fatalf("JSON diagnostics are not parseable: %q", stderr.String())
	}
}

func clearAuthenticationEnvironment(t *testing.T) {
	t.Helper()
	for _, name := range []string{"EXPENSIFY_AUTH_TOKEN", "EXPENSIFY_PARTNER_USER_ID", "EXPENSIFY_PARTNER_USER_SECRET"} {
		t.Setenv(name, "")
	}
}

func authObject(t *testing.T, args ...string) map[string]any {
	t.Helper()
	code, out, stderr := invoke(t, append(args, "--json")...)
	if code != 0 || stderr != "" {
		t.Fatalf("%v: exit=%d out=%q stderr=%q", args, code, out, stderr)
	}
	var value map[string]any
	if err := json.Unmarshal([]byte(out), &value); err != nil {
		t.Fatal(err)
	}
	return value
}

func TestAuthStatusReportsActualCredentialStorage(t *testing.T) {
	for _, storage := range []string{"file", "keyring"} {
		t.Run(storage, func(t *testing.T) {
			clearAuthenticationEnvironment(t)
			t.Setenv("EXPENSIFY_CONFIG_DIR", privateTempDir(t))
			t.Setenv("EXPENSIFY_CREDENTIAL_STORE", storage)
			if storage == "keyring" {
				keyring.MockInit()
				t.Cleanup(func() { keyring.MockInitWithError(errors.New("unexpected test keyring access")) })
			}
			store := config.New("")
			if err := store.Save(config.Credentials{AuthToken: "private-session"}); err != nil {
				t.Fatal(err)
			}
			value := authObject(t, "auth", "status")
			path := ""
			if storage == "file" {
				path = store.Path()
			}
			if value["storage"] != storage || value["source"] != "stored" || value["path"] != path || value["authenticated"] != true {
				t.Fatalf("unexpected storage: %#v", value)
			}
			logout := authObject(t, "auth", "logout")
			if logout["storage"] != "none" || logout["path"] != "" {
				t.Fatalf("logout reports stored credentials: %#v", logout)
			}
			value = authObject(t, "auth", "status")
			if value["storage"] != "none" || value["source"] != "none" || value["path"] != "" || value["authenticated"] != false {
				t.Fatalf("logout left credentials: %#v", value)
			}
		})
	}
}

