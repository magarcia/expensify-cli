func TestAuthDryRunDoesNotReadOrMigrateCredentials(t *testing.T) {
	clearAuthenticationEnvironment(t)
	t.Setenv("EXPENSIFY_CONFIG_DIR", privateTempDir(t))
	store := config.New("")
	if err := store.Save(config.Credentials{AuthToken: "original"}); err != nil {
		t.Fatal(err)
	}
	const invalidCredentials = "not valid credential JSON"
	if err := os.WriteFile(store.Path(), []byte(invalidCredentials), 0o600); err != nil {
		t.Fatal(err)
	}
	for _, selection := range []string{"auto", "keyring", "file"} {
		t.Setenv("EXPENSIFY_CREDENTIAL_STORE", selection)
		for _, args := range [][]string{{"auth", "login", "--credentials-stdin"}, {"auth", "status"}, {"auth", "status", "--check"}, {"auth", "logout"}} {
			value := authObject(t, append(args, "--dry-run")...)
			if value["dryRun"] != true || value["credentialStore"] != selection || value["fallbackPath"] != store.Path() {
				t.Fatalf("unexpected preview: %#v", value)
			}
		}
	}
	data, err := os.ReadFile(store.Path())
	if err != nil || string(data) != invalidCredentials {
		t.Fatalf("dry run changed credentials: %v", err)
	}
}

